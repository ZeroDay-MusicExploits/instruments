export const GLYPH_H = 7;

export function glyphWidth(ch) {
  const g = GLYPHS[ch];
  return g ? g[0].length : 5;
}

// Dibuja texto (ya en mayúsculas/ASCII) sobre un Canvas (tools/lib/png.mjs) con escala entera.
export function drawText(canvas, text, x, y, scale, hex, alpha = 255) {
  let cx = x;
  for (const ch of text) {
    const g = GLYPHS[ch] || GLYPHS[' '];
    for (let row = 0; row < g.length; row++) {
      const line = g[row];
      for (let col = 0; col < line.length; col++) {
        if (line[col] === '#') canvas.fillRect(cx + col * scale, y + row * scale, scale, scale, hex, alpha);
      }
    }
    cx += (glyphWidth(ch) + 1) * scale;
  }
  return cx - x;
}

export function textWidth(text, scale) {
  let w = 0;
  for (const ch of text) w += (glyphWidth(ch) + 1) * scale;
  return w - scale;
}

// Quita diacríticos y pasa a mayúsculas; cualquier char fuera del set queda como espacio.
export function toOgSafe(str) {
  const up = str
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toUpperCase();
  let out = '';
  for (const ch of up) out += GLYPHS[ch] ? ch : ch === '\n' ? '\n' : ' ';
  return out;
}
